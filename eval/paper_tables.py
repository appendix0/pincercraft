#!/usr/bin/env python3
"""Emit the manuscript's tables as LaTeX, straight from the ledger.

    python3 eval/paper_tables.py [--out docs/paper/manuscript/tables]

Every table body the paper \\input{}s is generated here. Nothing in the .tex
carries a transcribed figure.

This is not tidiness. results.md opens by promising that every number in it is
regenerated by a script, and §10's four robustness intervals were nonetheless
hand-transcribed for weeks -- correct, but unreproducible, which is the opposite
of the claim. A manuscript is a third copy of the same numbers and the furthest
from the data, so it is where that drift would land next and be hardest to
catch. Generating the tables removes the possibility rather than the temptation.

Each emitted file carries a header naming the command that produced it, so a
reader of the .tex source can see the number is derived rather than typed.
"""
import argparse, os, sqlite3, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from eval_db import DB_PATH as DB                                    # noqa: E402
from campaign_report import (load, by_arm, wilson, cluster_bootstrap,  # noqa: E402
                             holm, label, LAYER_ARMS, BOOTSTRAP_N)
from analysis_rules import (LAYER_ENDPOINT, MEI, is_category,        # noqa: E402
                            category_of, excluded_task_name)

HEADER = ('%% GENERATED by `python3 eval/paper_tables.py` -- do not edit.\n'
          '%% Regenerate rather than correct: a hand-edit here is a number the\n'
          '%% ledger no longer backs.\n')
ARM_ORDER = ['on', 'off', 'perception', 'gates', 'reflexes', 'verify', 'autofinish']


def pct(x):
    return f'{100 * x:.1f}'


def signed(x):
    """A signed number with a real minus sign.

    In LaTeX text mode an ASCII '-' sets a hyphen, not a minus, so a bare
    "-41.3pp" renders the headline effect with a word-joining dash. Both signs
    go through math mode: they are equal-width in the roman fonts, so the
    right-aligned columns still line up.
    """
    s = f'{100 * x:+.1f}'
    return ('$-$' if s[0] == '-' else '$+$') + s[1:]


def emit(out_dir, name, lines):
    path = os.path.join(out_dir, name)
    with open(path, 'w') as f:
        # Trailing '%' comments out the final newline so the fragment emits no
        # stray space token after its last row. Standard hygiene for a LaTeX
        # fragment read in the middle of a tabular. Note this is NOT what makes
        # \bottomrule work after the read -- LaTeX's \input appends a \relax
        # that starts a spurious row, so main.tex reads these with the TeX
        # primitive instead (see \inputrows there).
        f.write(HEADER + '\n'.join(lines) + '%\n')
    print(f'  wrote {name}')


def t_arms(groups, out_dir):
    rows = []
    for arm in ARM_ORDER:
        rs = groups.get(arm)
        if not rs:
            continue
        n = len(rs)
        k = sum(1 for r in rs if r['success'])
        lo, hi = wilson(k, n)
        claim = sum(r['claimed'] for r in rs)
        b = sum(1 for r in rs if r['claimed'] and not r['success'])
        c = sum(1 for r in rs if not r['claimed'] and r['success'])
        bold = r'\bfseries ' if arm in ('on', 'off') else ''
        rows.append(
            f'{bold}{label(arm)} & {n} & {pct(k/n)} & [{pct(lo)}, {pct(hi)}] & '
            f'{pct(claim/n)} & {b} & {c} & {pct((b-c)/n)} & {pct(b/n)} \\\\')
    emit(out_dir, 'arms.tex', rows)


def t_calibration(out_dir):
    """The 2.1 cells. Imported rather than recomputed."""
    from calib_report import load_labels, load_abstentions
    from calib_sample import draw_strata, cell as cell_of, path_of
    con = sqlite3.connect(DB)
    con.row_factory = sqlite3.Row
    picked, elig, _ = draw_strata(con)
    labels, abst = load_labels(con), load_abstentions()
    by_tid = {r['task_id']: r for r in elig}

    agg, pop = {}, {}
    for key, ids in picked.items():
        ok = n = 0
        for t in ids:
            if t in abst or t not in labels:
                continue
            n += 1
            ok += (labels[t] == bool(by_tid[t]['success']))
        agg[key] = (ok, n)
    for r in elig:
        k = (cell_of(r), path_of(r))
        pop[k] = pop.get(k, 0) + 1

    def line(name, keys, indent=False):
        ok = sum(agg.get(k, (0, 0))[0] for k in keys)
        n = sum(agg.get(k, (0, 0))[1] for k in keys)
        npop = sum(pop.get(k, 0) for k in keys)
        if not n:
            return f'{name} & {npop} & 0 & --- & --- \\\\'
        lo, hi = wilson(ok, n)
        pre = r'\hspace{1em}$\hookrightarrow$ ' if indent else ''
        return (f'{pre}{name} & {npop} & {n} & {ok}/{n} = {pct(ok/n)}\\% & '
                f'[{pct(lo)}, {pct(hi)}] \\\\')

    rows = [
        line(r'\bfseries scorer says false completion',
             [('B', 'inventory'), ('B', 'blockscan')]),
        line('inventory-delta path', [('B', 'inventory')], indent=True),
        line('block-scan path', [('B', 'blockscan')], indent=True),
        line('scorer says success', [('A', 'inventory'), ('A', 'blockscan')]),
        line('scorer says fail, no claim',
             [('C', 'inventory'), ('C', 'blockscan')]),
    ]
    emit(out_dir, 'calibration.tex', rows)


def t_layers(groups, out_dir):
    platform = excluded_task_name('bench')
    plat = lambda rs: [r for r in rs if r['task_name'] != platform]  # noqa: E731
    present = [a for a in LAYER_ARMS if a in groups and a != 'measurement']
    res, ps = {}, []
    for arm in present:
        b = cluster_bootstrap(groups[arm], groups['on'],
                              value=is_category(LAYER_ENDPOINT[arm]))
        if b:
            res[arm] = b
            ps.append((arm, b['p']))
    rows = []
    for arm, p, adj in holm(ps):
        b = res[arm]
        d = cluster_bootstrap(plat(groups[arm]), plat(groups['on']),
                              value=is_category(LAYER_ENDPOINT[arm]))
        drop = ('---' if not d else
                f'{signed(d["diff"])} [{signed(d["lo"])}, {signed(d["hi"])}]')
        verdict = ('bounded null' if b['hi'] < MEI else
                   'dominant' if (b['lo'] > 0 and b['diff'] >= MEI) else
                   'inconclusive')
        rows.append(
            f'{label(arm)} & {LAYER_ENDPOINT[arm].replace("_", " ")} & '
            f'{signed(b["diff"])} & [{signed(b["lo"])}, {signed(b["hi"])}] & '
            f'{adj:.4f} & {verdict} & {drop} \\\\')
    emit(out_dir, 'layers.tex', rows)


def t_taxonomy(groups, out_dir):
    cats = ['true_completion', 'false_completion', 'reached_not_recognized',
            'capability_failure', 'budget_exhaustion']
    rows = []
    for arm in ARM_ORDER:
        rs = groups.get(arm)
        if not rs:
            continue
        counts = {c: 0 for c in cats}
        for r in rs:
            c = category_of(r)
            if c in counts:
                counts[c] += 1
        rows.append(f'{label(arm)} & {len(rs)} & ' +
                    ' & '.join(str(counts[c]) for c in cats) + r' \\')
    emit(out_dir, 'taxonomy.tex', rows)


def t_cost(groups, out_dir):
    rows = []
    for arm in ARM_ORDER:
        rs = groups.get(arm)
        if not rs:
            continue
        n = len(rs)
        k = sum(1 for r in rs if r['success'])
        tin = sum(r['input_tokens'] or 0 for r in rs)
        sec = sum(r['wall_clock_seconds'] or 0 for r in rs)
        per = f'{tin / k:,.0f}' if k else '---'
        rows.append(f'{label(arm)} & {tin/n:,.0f} & {sec/n:.1f} & {per} \\\\')
    emit(out_dir, 'cost.tex', rows)


def t_headline(groups, out_dir, n_primary):
    """Macros, so the prose cannot drift from the tables."""
    on, off = groups['on'], groups['off']
    succ = lambda r: 1 if r['success'] else 0      # noqa: E731
    fc = is_category('false_completion')
    bs = cluster_bootstrap(on, off, value=succ)
    bf = cluster_bootstrap(on, off, value=fc)
    m = [
        # The whole primary set across all seven arms -- NOT on+off, which is
        # the two-arm comparison and would understate the campaign by 3.5x
        # wherever the prose says "356 attempts".
        r'\newcommand{\NPrimary}{%d}' % n_primary,
        r'\newcommand{\NArms}{%d}' % len(groups),
        r'\newcommand{\OnN}{%d}' % len(on),
        r'\newcommand{\OffN}{%d}' % len(off),
        r'\newcommand{\OnSucc}{%s\%%}' % pct(sum(succ(r) for r in on) / len(on)),
        r'\newcommand{\OffSucc}{%s\%%}' % pct(sum(succ(r) for r in off) / len(off)),
        r'\newcommand{\OnClaim}{%s\%%}' % pct(sum(r['claimed'] for r in on) / len(on)),
        r'\newcommand{\OffClaim}{%s\%%}' % pct(sum(r['claimed'] for r in off) / len(off)),
        r'\newcommand{\OnFC}{%s\%%}' % pct(sum(fc(r) for r in on) / len(on)),
        r'\newcommand{\OffFC}{%s\%%}' % pct(sum(fc(r) for r in off) / len(off)),
        r'\newcommand{\SuccDiff}{%spp}' % signed(bs['diff']),
        r'\newcommand{\SuccCI}{[%s, %s]}' % (signed(bs['lo']), signed(bs['hi'])),
        r'\newcommand{\FCDiff}{%spp}' % signed(bf['diff']),
        r'\newcommand{\FCCI}{[%s, %s]}' % (signed(bf['lo']), signed(bf['hi'])),
        r'\newcommand{\Resamples}{%s}' % f'{BOOTSTRAP_N:,}',
    ]
    emit(out_dir, 'macros.tex', m)


def main(out_dir):
    con = sqlite3.connect(DB)
    con.row_factory = sqlite3.Row
    rows = load(con, None, 'conf')
    primary = [r for r in rows if not r['discarded'] and not r['excluded']]
    groups = by_arm(primary)
    os.makedirs(out_dir, exist_ok=True)
    print(f'generating from {len(primary)} primary attempts:')
    t_headline(groups, out_dir, len(primary))
    t_arms(groups, out_dir)
    t_calibration(out_dir)
    t_layers(groups, out_dir)
    t_taxonomy(groups, out_dir)
    t_cost(groups, out_dir)


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        'docs', 'paper', 'manuscript', 'tables'))
    main(ap.parse_args().out)
