#!/usr/bin/env python3
"""Design-based permutation test — a cross-check on the cluster bootstrap.

    python3 eval/permutation_test.py [--tag conf]

Why. The headline intervals come from a cluster bootstrap resampling **13 task
clusters**. Conventional guidance for a cluster bootstrap is 30-50+ clusters, so
at 13 its coverage is likely optimistic, and its p is obtained by inverting the
estimate's sampling distribution rather than by constructing a null — standard
practice, but an approximation. A permutation test needs neither assumption: it
builds the null distribution directly out of the experiment's own randomisation.

The randomisation to mimic. Arms are interleaved within a replicate and every
arm runs the same task set, so for a given (replicate, task) the full-harness
and no-harness attempts form a matched pair. Under the null that the harness
does nothing, the two labels within a pair are exchangeable — so the null
distribution is generated by independently flipping each pair's labels, which is
exactly the paired randomisation (sign-flip) test and the design-based analogue
of the McNemar already reported in §6.

This does NOT assume attempts are independent across tasks, which is the
assumption the 13-cluster bootstrap is being cross-checked for.
"""
import argparse, os, random, sqlite3, sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from eval_db import DB_PATH as DB                      # noqa: E402
from campaign_report import load, by_arm               # noqa: E402
from analysis_rules import is_category                 # noqa: E402

B = 10000
SEED = 12345          # the same seed the cluster bootstrap uses, for consistency


def paired_cells(on, off, value):
    """[(on_value, off_value)] per (replicate, task) with both arms present."""
    def index(rows):
        d = defaultdict(list)
        for r in rows:
            d[(r['seed'], r['task_name'])].append(value(r))
        return d
    a, b = index(on), index(off)
    out = []
    for k in sorted(set(a) & set(b)):
        # Mean within cell: a replicate x task cell normally holds one attempt
        # per arm, but averaging keeps the test well defined if it ever holds
        # more, rather than silently taking the first.
        out.append((sum(a[k]) / len(a[k]), sum(b[k]) / len(b[k])))
    return out


def permutation(cells, rng):
    obs = sum(x - y for x, y in cells) / len(cells)
    hits = 0
    for _ in range(B):
        s = 0.0
        for x, y in cells:
            s += (x - y) if rng.random() < 0.5 else (y - x)
        if abs(s / len(cells)) >= abs(obs) - 1e-12:
            hits += 1
    # (r+1)/(B+1), and the two-sided floor is 1/(B+1) here because the statistic
    # is not doubled -- unlike the bootstrap p in campaign_report, whose floor is
    # 2/(B+1). Reported as "<=" at the floor for the same reason.
    return obs, (hits + 1) / (B + 1)


def main(tag):
    con = sqlite3.connect(DB)
    con.row_factory = sqlite3.Row
    rows = load(con, None, tag)
    primary = [r for r in rows if not r['discarded'] and not r['excluded']]
    groups = by_arm(primary)
    on, off = groups.get('on', []), groups.get('off', [])
    if not on or not off:
        sys.exit('need both the full-harness and no-harness arms')

    rng = random.Random(SEED)
    print('=' * 74)
    print('PERMUTATION TEST — paired within (replicate x task)'.center(74))
    print('=' * 74)
    print('\n%-22s %8s %12s %10s %12s' %
          ('endpoint', 'pairs', 'observed', 'perm p', 'bootstrap p'))
    floor = 1.0 / (B + 1)
    for name, value, boot in (
            ('task success', lambda r: 1 if r['success'] else 0, '<=0.0002'),
            ('false completion', is_category('false_completion'), '<=0.0002')):
        cells = paired_cells(on, off, value)
        obs, p = permutation(cells, rng)
        ps = f'<={floor:.4f}' if p <= floor else f'={p:.4f}'
        print('%-22s %8d %+11.1fpp %10s %12s'
              % (name, len(cells), 100 * obs, ps, boot))
    print('\n  Sign-flip over matched (replicate x task) pairs, %d permutations,'
          ' seed %d.' % (B, SEED))
    print('  Makes no independence assumption across tasks, so it does not inherit')
    print('  the 13-cluster concern the bootstrap carries. Agreement between the')
    print('  two is the point: they fail in different ways.')
    print('\n  NOT RUN: the GLMM cross-check (success ~ arm + (1|task) +')
    print('  (1|replicate)). It needs statsmodels, and this analysis path is')
    print('  deliberately stdlib-only so every reported number reproduces with a')
    print('  bare python3. Recorded as an open item rather than silently skipped.')


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--tag', default='conf')
    main(ap.parse_args().tag)
